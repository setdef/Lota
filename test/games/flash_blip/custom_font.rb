  @char_width = 6
  @char_height = 8
  @tracking = 1 # Horizontal space between characters
  @space_width = 2 # Custom width for space
  @glyph_widths = {} # Will store actual widths

  class << self
    attr_reader :glyphs, :char_width, :char_height, :tracking, :space_width, :glyph_widths
  end

  def self.init
    glyphs.each do |char, glyph|
      if char == " "
        glyph_widths[char] = space_width
      else
        max_width = 0
        glyph.each do |row_str|
          row_str.length.downto(1) do |col|
            if row_str[col - 1] != " "
              max_width = [max_width, col].max
              break
            end
          end
        end
        glyph_widths[char] = max_width
      end
    end
  end
