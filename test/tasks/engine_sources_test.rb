require_relative "tree_helper"
require_relative "../../tasks/engine_sources"

class EngineSourcesTest < Minitest::Test
  include TreeHelper

  # Each test evaluates its own tree, so the CMake runs can overlap.
  parallelize_me!

  # A miniature of LÖVE's tree: one file each rule keeps out, a neighbor
  # each rule must keep, a source only -DMEGA=ON adds, and on macOS, where
  # CMake compiles it, an Objective-C++ source.
  KEPT = (%w[
    src/common/Data.cpp
    src/common/runtimes.cpp
    src/libraries/enet/host.c
    src/libraries/lz4/lz4.c
    src/modules/graphics/Graphics.cpp
    src/modules/lovely/Lovely.cpp
    src/modules/physics/box2d/World.cpp
    src/modules/thread/threads.cpp
    src/modules/thread/sdl/Thread.cpp
    src/mega.cpp
  ] + (RUBY_PLATFORM.include?("darwin") ? %w[src/modules/window/macos.mm] : [])).freeze

  DROPPED = {
    "src/modules/graphics/wrap_Graphics.cpp" => "Lua binding (wrap_*), ADR 001 section 1",
    "src/common/runtime.cpp" => "Lua glue, ADR 001 section 1",
    "src/common/Reference.cpp" => "Lua glue, ADR 001 section 1",
    "src/modules/love/love.cpp" => "Lua boot sequence, ADR 001 section 1",
    "src/modules/thread/LuaThread.cpp" => "Lua threads and channels, ADR 001 section 1",
    "src/modules/thread/ThreadModule.cpp" => "Lua threads and channels, ADR 001 section 1",
    "src/modules/thread/Channel.cpp" => "Lua threads and channels, ADR 001 section 1",
    "src/libraries/enet/enet.cpp" => "lua-enet binding, ADR 001 section 1",
    "src/modules/physics/box2d/wrap_World.cpp" => "Lua binding (wrap_*), ADR 001 section 1",
    "src/love.cpp" => "main() of the love executable, which boots Lua",
    "src/libraries/lua53/lstrlib.c" => "Lua, or a library only Lua calls",
    "src/libraries/luasocket/luasocket.cpp" => "Lua, or a library only Lua calls",
    "src/libraries/luahttps/src/lua/main.cpp" => "Lua, or a library only Lua calls",
  }.freeze

  def love_tree(root, extra: [])
    sources = KEPT - ["src/mega.cpp"] + DROPPED.keys - ["src/love.cpp"] + extra
    (sources + KEPT + DROPPED.keys).uniq.each { |path| write(root, path) }
    write(root, "src/common/Data.h")
    write(root, "CMakeLists.txt", <<~CMAKE)
      cmake_minimum_required(VERSION 3.19)
      project(fake C CXX)
      # Objective-C++ compiles only where Apple's compilers are, as for
      # LÖVE's macOS sources.
      if(APPLE)
        enable_language(OBJCXX)
      endif()
      add_library(engine STATIC #{sources.join(' ')} src/common/Data.h)
      add_library(shared_twice STATIC src/common/Data.cpp)
      add_library(interface_only INTERFACE)
      add_executable(love src/love.cpp)
      if(MEGA)
        add_library(mega STATIC src/mega.cpp)
      endif()
    CMAKE
  end

  def sources(root, label: "fake tree")
    EngineSources.new(source: root, build: File.join(root, "build"), cmake_args: %w[-DMEGA=ON], label:)
  end

  def test_generate_lists_every_kept_source_once_sorted
    in_tree do |root|
      love_tree(root)

      assert_equal KEPT.sort, EngineSources.listed(sources(root).generate)
    end
  end

  def test_generate_lists_every_dropped_source_with_its_reason
    in_tree do |root|
      love_tree(root)
      excluded = sources(root).generate.split("# Excluded:\n").last.lines.map(&:strip)

      assert_equal(DROPPED.sort.map { |path, reason| "#   #{path}: #{reason}".strip }, excluded)
    end
  end

  def test_generate_renders_a_cmake_list_under_a_generated_header
    in_tree do |root|
      love_tree(root)
      generated = sources(root, label: "fake tree at abc123").generate

      assert_match(%r{\A# GENERATED by `rake engine:sources` \(tasks/engine_sources\.rb\)\. Do not edit\.\n}, generated)
      assert_includes generated, "#   fake tree at abc123,\n"
      assert_includes generated, "set(ENGINE_SOURCES\n\t${ENGINE_SOURCE_DIR}/src/common/Data.cpp\n"
      assert_includes generated, "\t${ENGINE_SOURCE_DIR}/#{KEPT.max}\n)\n"
    end
  end

  def test_generate_raises_when_cmake_cannot_evaluate_the_tree
    in_tree do |root|
      write(root, "CMakeLists.txt", "message(FATAL_ERROR \"no such tree\")\n")

      error = assert_raises(EngineSources::Failure) { sources(root).generate }
      assert_includes error.message, "no such tree"
    end
  end

  def test_generate_forgets_targets_from_an_earlier_evaluation
    in_tree do |root|
      love_tree(root)
      sources(root).generate
      write(root, "CMakeLists.txt", "cmake_minimum_required(VERSION 3.19)\nproject(fake C)\n" \
        "add_library(engine STATIC src/libraries/lz4/lz4.c)\n")

      assert_equal %w[src/libraries/lz4/lz4.c], EngineSources.listed(sources(root).generate)
    end
  end

  def test_write_creates_the_file_and_problems_finds_none
    in_tree do |root|
      love_tree(root)
      list = File.join(root, "out", "sources_test.cmake")
      sources(root).write(list)

      assert_equal sources(root).generate, File.read(list)
      assert_empty sources(root).problems(list)
    end
  end

  def test_problems_reports_a_missing_list
    in_tree do |root|
      love_tree(root)
      list = File.join(root, "sources_test.cmake")

      assert_equal ["#{list} does not exist; generate it"], sources(root).problems(list)
    end
  end

  def test_problems_reports_a_listed_file_that_no_longer_exists
    in_tree do |root|
      love_tree(root)
      list = File.join(root, "sources_test.cmake")
      sources(root).write(list)
      File.delete(File.join(root, "src/modules/graphics/Graphics.cpp"))

      assert_equal ["#{list} lists src/modules/graphics/Graphics.cpp, which no longer exists"],
        sources(root).problems(list)
    end
  end

  def test_problems_reports_a_source_the_tree_added
    in_tree do |root|
      love_tree(root)
      list = File.join(root, "sources_test.cmake")
      sources(root).write(list)
      love_tree(root, extra: %w[src/modules/graphics/Canvas.cpp src/modules/graphics/wrap_Canvas.cpp])

      expected = [
        "+ \t${ENGINE_SOURCE_DIR}/src/modules/graphics/Canvas.cpp",
        "+ #   src/modules/graphics/wrap_Canvas.cpp: Lua binding (wrap_*), ADR 001 section 1",
      ]
      assert_equal expected, sources(root).problems(list)
    end
  end

  def test_difference_marks_removed_and_added_lines
    assert_equal ["- b", "+ c"], EngineSources.difference("a\nb\n", "a\nc\n")
    assert_empty EngineSources.difference("a\n", "a\n")
  end

  def test_listed_reads_only_indented_engine_source_dir_paths
    content = "set(ENGINE_SOURCES\n\t${ENGINE_SOURCE_DIR}/src/a.cpp\n\t${ENGINE_SOURCE_DIR}/src/b.mm\n)\n" \
      "#   src/wrap_c.cpp: reason\n\t${OTHER}/src/d.cpp\n"

    assert_equal %w[src/a.cpp src/b.mm], EngineSources.listed(content)
  end

  def test_reason_matches_whole_names_only
    engine = EngineSources.new(source: ".", build: "build")

    assert_equal "Lua binding (wrap_*), ADR 001 section 1", engine.reason("wrap_top.cpp")
    assert_nil engine.reason("src/modules/graphics/unwrap_Graphics.cpp")
    assert_nil engine.reason("src/modules/thread/sdl/threads.cpp")
    assert_nil engine.reason("src/libraries/enet/enet.cpp.in")
    assert_nil engine.reason("src/love.cpp.in")
    assert_nil engine.reason("vendor/src/common/runtime.cpp")
  end

  def test_platform_names_macos_linux_and_windows_and_refuses_other_hosts
    assert_equal "macos", EngineSources.platform("darwin25")
    assert_equal "linux", EngineSources.platform("linux-gnu")
    assert_equal "windows", EngineSources.platform("mingw32")

    error = assert_raises(EngineSources::Failure) { EngineSources.platform("mswin64_140") }
    assert_equal "Lota builds its engine on macOS, Linux, and Windows with MinGW only, not mswin64_140",
      error.message
  end

  def test_linux_evaluates_without_luajit
    assert_equal %w[-G Ninja -DMEGA=ON], EngineSources.cmake_args("macos")
    assert_equal %w[-G Ninja -DMEGA=ON -DLOVE_JIT=OFF], EngineSources.cmake_args("linux")
  end

  # iOS's list comes from CMake's own cross-compiling for iOS, on a Mac,
  # beside macOS's.
  def test_ios_evaluates_for_the_arm64_simulator_and_is_generated_on_macos
    ios = %w[-DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT=iphonesimulator -DCMAKE_OSX_ARCHITECTURES=arm64]

    assert_equal %w[-G Ninja -DMEGA=ON] + ios, EngineSources.cmake_args("ios")
    assert_equal %w[macos ios], EngineSources.generated_on("macos")
    assert_equal %w[linux], EngineSources.generated_on("linux")
    assert_equal %w[windows], EngineSources.generated_on("windows")
  end

  # LÖVE's Windows install rules name megasource's SDL3 target, which the
  # evaluation stands in for.
  def test_windows_evaluates_without_luajit_with_a_stand_in_for_megasources_sdl
    args = EngineSources.cmake_args("windows")

    assert_equal %w[-G Ninja -DMEGA=ON -DLOVE_JIT=OFF -DMEGA_SDL3=lota_sdl3_stand_in], args.first(5)
    assert_equal "-DCMAKE_PROJECT_INCLUDE=#{File.join(ROOT, 'tasks/engine_sources_windows.cmake')}", args.last
  end

  # A generated list names no path of the machine that generated it.
  def test_label_names_the_commit_and_what_cmake_is_told_but_no_path
    assert_equal "vendor/love abc on linux with -DMEGA=ON -DLOVE_JIT=OFF", EngineSources.label("abc", "linux")
    assert_equal "vendor/love abc on windows with -DMEGA=ON -DLOVE_JIT=OFF -DMEGA_SDL3=lota_sdl3_stand_in",
      EngineSources.label("abc", "windows")
  end

  # Ruby on Windows writes each newline as CRLF in text mode.
  def test_write_writes_the_generated_bytes
    in_tree do |root|
      love_tree(root)
      list = File.join(root, "sources_test.cmake")
      sources(root).write(list)

      assert_equal sources(root).generate.b, File.binread(list)
    end
  end
end
